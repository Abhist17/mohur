// Copies contract ABIs (from forge's out/) and deployment addresses into src/generated.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contracts = join(here, "..", "..", "contracts");
const out = join(contracts, "out");
const gen = join(here, "..", "src", "generated");

const names = {
  UnisonHook: "UnisonHook.sol",
  UnisonHookFactory: "UnisonHookFactory.sol",
  UnisonLens: "UnisonLens.sol",
  UnisonLoopRouter: "UnisonLoopRouter.sol",
  UnisonSwapVMRouter: "UnisonSwapVMRouter.sol",
  UnisonTestToken: "UnisonTestToken.sol",
  Aqua: "Aqua.sol",
};
let abis = "// generated by scripts/sync.mjs - do not edit\n";
for (const [name, file] of Object.entries(names)) {
  const art = JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
  abis += `export const ${name}Abi = ${JSON.stringify(art.abi)} as const;\n`;
}
writeFileSync(join(gen, "abis.ts"), abis);

const deployments = {};
for (const net of ["local", "base-sepolia"]) {
  const p = join(contracts, "deployments", `${net}.json`);
  if (existsSync(p)) deployments[net] = JSON.parse(readFileSync(p, "utf8"));
}
writeFileSync(
  join(gen, "deployments.ts"),
  "// generated by scripts/sync.mjs - do not edit\n" +
    "export type Deployment = { chainId: number; startBlock: number; poolManager: `0x${string}`; aqua: `0x${string}`; swapVM: `0x${string}`; hookFactory: `0x${string}`; lens: `0x${string}`; loopRouter: `0x${string}`; tWETH: `0x${string}`; tWBTC: `0x${string}`; tUSDC: `0x${string}`; demoHook?: `0x${string}`; demoMaker?: `0x${string}` };\n" +
    `export const deployments: Record<string, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);
console.log("synced ABIs and deployments for:", Object.keys(deployments).join(", ") || "(none)");
